//! The `coordinator init` subcommand: scaffold a ready-to-run coordinator.
//!
//! Generates a fresh ed25519 signing seed and a populated `coordinator.toml`
//! pointing at it, under the coordinator's per-role config/data subdir
//! (`<config>/coordinator/`, `<data>/coordinator/`) or explicit overrides.
//! Secrets are written with `0600` permissions on unix.
//!
//! **No TLS material is generated any more.** The private CA is gone with mTLS
//! (architecture §6.2), and the expected deployment terminates TLS at a reverse
//! proxy in front of the coordinator (§3.5), so there is nothing for `init` to
//! mint. A self-hosted operator who wants the coordinator to terminate TLS
//! itself supplies a certificate and adds the commented-out `[tls]` block.

use std::path::Path;

use anyhow::{bail, Context, Result};

use fleet_core::policy::Policy;

use crate::cli::InitArgs;
use crate::paths;
use crate::secrets::{generate_seed_hex, toml_path, write_public, write_secret};

/// Names of the files `init` writes, relative to the config / data dirs.
const SIGNING_SEED_FILE: &str = "signing.seed";
const SQLITE_FILE: &str = "coordinator.sqlite";
const CONFIG_FILE: &str = "coordinator.toml";

/// The default listen address: loopback, because the expected deployment is
/// behind a proxy on the same host and binding a public interface should be a
/// deliberate act rather than a default.
const DEFAULT_LISTEN_ADDR: &str = "127.0.0.1:7000";

/// Run `coordinator init`.
///
/// # Errors
///
/// Returns an error if directories cannot be created, key generation fails, or
/// (without `--force`) any target file already exists.
pub fn run(args: InitArgs) -> Result<()> {
    let config_dir = match args.config_dir {
        Some(dir) => dir,
        None => paths::coordinator_config_dir()?,
    };
    let data_dir = match args.data_dir {
        Some(dir) => dir,
        None => paths::coordinator_data_dir()?,
    };

    std::fs::create_dir_all(&config_dir)
        .with_context(|| format!("creating config dir {}", config_dir.display()))?;
    std::fs::create_dir_all(&data_dir)
        .with_context(|| format!("creating data dir {}", data_dir.display()))?;

    let config_path = config_dir.join(CONFIG_FILE);
    let seed_path = data_dir.join(SIGNING_SEED_FILE);
    let sqlite_path = data_dir.join(SQLITE_FILE);

    // Idempotency guard: refuse to clobber existing files unless --force.
    if !args.force {
        let existing: Vec<&Path> = [config_path.as_path(), seed_path.as_path()]
            .into_iter()
            .filter(|p| p.exists())
            .collect();
        if !existing.is_empty() {
            let list = existing
                .iter()
                .map(|p| p.display().to_string())
                .collect::<Vec<_>>()
                .join("\n  ");
            bail!("refusing to overwrite existing file(s); pass --force to regenerate:\n  {list}");
        }
    }

    // Signing seed: 32 random bytes -> 64 lowercase hex chars.
    let seed_hex = generate_seed_hex();
    write_secret(&seed_path, seed_hex.as_bytes())
        .with_context(|| format!("writing signing seed {}", seed_path.display()))?;

    let public_url = args
        .public_url
        .unwrap_or_else(|| format!("http://{DEFAULT_LISTEN_ADDR}"));

    let config_toml =
        render_coordinator_config(&public_url, &sqlite_path, &seed_path, &Policy::default())?;
    write_public(&config_path, config_toml.as_bytes())
        .with_context(|| format!("writing config {}", config_path.display()))?;

    print_summary(&config_path, &seed_path, &sqlite_path, &public_url);

    Ok(())
}

/// Render a populated `coordinator.toml` referencing the generated files.
fn render_coordinator_config(
    public_url: &str,
    sqlite_path: &Path,
    signing_key_path: &Path,
    policy: &Policy,
) -> Result<String> {
    let policy_toml = toml::to_string(policy).context("serialising default policy")?;
    let mut policy_block = String::new();
    for line in policy_toml.lines() {
        policy_block.push_str(line);
        policy_block.push('\n');
    }

    let config = format!(
        r#"# probe-rs-fleet coordinator config
#
# Generated by `probe-rs-fleet coordinator init`. Paths are absolute and point
# at the material generated alongside this file.

# TCP address the coordinator listens on.
#
# Loopback by default: the expected deployment puts an HTTPS reverse proxy in
# front (which terminates TLS and routes /agent, /client, /auth/* and /healthz),
# so the coordinator itself need not be reachable from outside the host.
listen_addr = "{DEFAULT_LISTEN_ADDR}"

# The externally reachable base URL agents and clients DIAL to reach this
# coordinator — what you pass to `login --fleet-url` / `node up --fleet-url`.
#
# Behind a proxy this is NOT derivable from `listen_addr`: the coordinator
# listens on loopback and the world reaches it at a name it never sees.
#
# For the CLI login this is NOT an OAuth callback origin: the GitHub device flow
# has no redirect_uri. For the web UI's BROWSER login it is: the callback is
# derived from this value as `<public_url>/auth/github/callback`, and never from
# the request's Host / X-Forwarded-Host header — behind a proxy that header is
# attacker-settable, and a redirect it controls is an account takeover.
public_url = {public_url}

# SQLite database file (created on first run).
sqlite_path = {sqlite_path}

# ed25519 capability-token signing seed (64 hex chars / 32 bytes).
# Alternatively inline the seed with `signing_key_hex = "<64 hex chars>"`.
signing_key_path = {signing_key_path}

# How often (seconds) the lease-expiry sweep runs.
# sweep_interval_secs = 5

# WebSocket keepalive. A reverse proxy reaps idle connections on a timeout we do
# not control, and a lab node's connection is idle most of the time, so this is
# load-bearing rather than cosmetic. `pong_timeout_secs` must exceed
# `ping_interval_secs`, or every idle connection is dropped before it can answer.
# ping_interval_secs = 20
# pong_timeout_secs  = 60

# How long (seconds) a user session token is valid before it must be refreshed.
# session_ttl_secs = 43200

# How old (seconds) a node token may get before the coordinator pushes a
# replacement down the established connection. The old token stays valid until
# the node acknowledges the new one, so a lost push costs a retry, not a visit.
# node_token_rotate_secs = 604800

# How long (seconds) a node registration awaiting interactive approval lives,
# and how many may wait at once. The short code is guessable by construction, so
# the TTL is short; the cap bounds what an unauthenticated caller can write.
# pending_node_ttl_secs = 900
# max_pending_nodes = 256

# Coordinator-terminated TLS. OMIT THIS TABLE when a reverse proxy terminates
# TLS (the expected deployment) — the coordinator then serves plain HTTP on
# loopback. Set both paths for a self-hosted deployment with no proxy:
#
# [tls]
# cert = "/path/to/fullchain.pem"
# key  = "/path/to/privkey.pem"
#
# With a self-signed certificate, clients need its SHA-256:
#   openssl x509 -in cert.pem -outform der | openssl dgst -sha256
# and pass it as `--server-cert-sha256` to `login` / `node up`.

# The GitHub OAuth app backing `probe-rs-fleet login` and the web UI.
#
# Omitting this block is a SUPPORTED deployment, not a broken one: an air-gapped
# or development fleet bootstraps with `coordinator user-token` instead, and the
# device-flow routes then answer 503 `device_flow_unconfigured` — a named code
# the CLI turns into "ask the operator, or use `coordinator user-token`".
#
# To enable login: register an OAuth app at
# https://github.com/settings/developers with "Enable Device Flow" TICKED.
# There is NO callback URL to configure for the CLI — the device flow has no
# redirect_uri.
#
# The web UI's BROWSER login needs exactly one extra step, the only
# per-deployment setup the device flow did not need: add
# `<public_url>/auth/github/callback` to the app's callback URLs, set a client
# secret, and set `callback_registered = true`. Skipping it is supported — the
# UI then falls back to the in-page device-code login.
#
# The coordinator brokers both flows, so the client id/secret never leave this
# host and the user's GitHub access token never leaves this process.
#
# [github]
# client_id = "Iv1.0123456789abcdef"
# # Only if your app requires one (OAuth Apps do not, for the device flow).
# # REQUIRED once `callback_registered = true`: GitHub refuses the
# # authorization-code exchange without it and implements no PKCE, so the
# # secret is also what makes an intercepted code unspendable.
# # client_secret = "…"
# # Scope to request. Empty is correct for identity-only login: `GET /user`
# # needs none, and asking for more than you use is hard for a user to undo.
# # scope = ""
# # You have added `<public_url>/auth/github/callback` to the OAuth app's
# # callback URLs. Default: false — an assertion the coordinator cannot verify,
# # and false means the web UI offers the device-code login rather than a
# # redirect that dead-ends on GitHub's "redirect_uri is not associated with
# # this application" page.
# # callback_registered = false
# # Endpoint overrides, for GitHub Enterprise. Defaults shown.
# # device_code_url  = "https://github.com/login/device/code"
# # access_token_url = "https://github.com/login/oauth/access_token"
# # authorize_url    = "https://github.com/login/oauth/authorize"
# # api_base         = "https://api.github.com"

# Lease scheduling policy (defaults shown).
[policy]
{policy_block}"#,
        public_url = toml::Value::String(public_url.to_owned()),
        sqlite_path = toml_path(sqlite_path),
        signing_key_path = toml_path(signing_key_path),
    );
    Ok(config)
}

/// Print a summary of what was written and the next steps.
fn print_summary(config_path: &Path, seed_path: &Path, sqlite_path: &Path, public_url: &str) {
    println!("Created coordinator scaffold:");
    println!("  config       {}", config_path.display());
    println!("  signing seed {}", seed_path.display());
    println!(
        "  sqlite (db)  {} (created on first run)",
        sqlite_path.display()
    );
    println!("  public URL   {public_url}");
    println!();
    println!("Next steps:");
    println!("  1. Register a GitHub OAuth app with DEVICE FLOW ENABLED, then");
    println!("     UNCOMMENT the [github] block and set client_id in");
    println!("       {}", config_path.display());
    println!("     (No callback URL is needed for the CLI login. For the web UI's");
    println!("     browser login, additionally register");
    println!("       {public_url}/auth/github/callback");
    println!("     set a client secret, and set callback_registered = true;");
    println!("     without that the web UI falls back to the device-code login.)");
    println!("  2. Start the coordinator (no --config needed):");
    println!("       probe-rs-fleet coordinator");
    println!("  3. Log in from your laptop:");
    println!("       probe-rs-fleet login --fleet-url {public_url}");
    println!("  4. Mint an auth key and enroll a node with it:");
    println!("       # on your laptop, after step 3:");
    println!("       probe-rs-fleet auth-key create --tag lab");
    println!("       # on the node:");
    println!("       probe-rs-fleet node up --fleet-url {public_url} --auth-key <key>");
    println!();
    println!("Without a GitHub app (air-gapped, or a quick trial), skip step 1 and");
    println!("bootstrap with the INTERIM verb instead:");
    println!("       probe-rs-fleet coordinator user-token <your-login>");
    println!("       probe-rs-fleet login --fleet-url {public_url} --token <token>");
    println!();
    println!("Note: `user-token` and `auth-key` mint credentials from a shell on");
    println!("this host, bypassing the login flow. They are the unattended /");
    println!("air-gapped escape hatch, not the front door. `coordinator auth-key`");
    println!("is no longer *needed* for step 4 — any member mints one over the API");
    println!("with `probe-rs-fleet auth-key create` — but it still works with no");
    println!("login at all, and it is the only way to mint a key that never expires.");
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config;

    fn init_into(dir: &Path, force: bool) -> Result<()> {
        run(InitArgs {
            config_dir: Some(dir.join("config")),
            data_dir: Some(dir.join("data")),
            public_url: Some("https://fleet.example".to_owned()),
            force,
        })
    }

    #[test]
    fn init_writes_config_and_seed_and_no_tls_material() {
        let tmp = tempfile::tempdir().unwrap();
        init_into(tmp.path(), false).unwrap();

        let config = tmp.path().join("config");
        let data = tmp.path().join("data");
        assert!(config.join(CONFIG_FILE).exists(), "missing {CONFIG_FILE}");
        assert!(data.join(SIGNING_SEED_FILE).exists());

        // The private CA is gone: `init` must not mint any certificate material.
        for stale in [
            "client-ca.pem",
            "client-ca-key.pem",
            "coordinator-cert.pem",
            "coordinator-key.pem",
        ] {
            assert!(
                !data.join(stale).exists(),
                "{stale} must not be generated any more"
            );
        }
    }

    #[cfg(unix)]
    #[test]
    fn secrets_are_0600() {
        use std::os::unix::fs::PermissionsExt;
        let tmp = tempfile::tempdir().unwrap();
        init_into(tmp.path(), false).unwrap();
        let data = tmp.path().join("data");
        let mode = std::fs::metadata(data.join(SIGNING_SEED_FILE))
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o777, 0o600, "seed perms = {:o}", mode & 0o777);
    }

    #[test]
    fn generated_config_round_trips() {
        let tmp = tempfile::tempdir().unwrap();
        init_into(tmp.path(), false).unwrap();
        let config_path = tmp.path().join("config").join(CONFIG_FILE);
        let cfg = config::load_coordinator_config(&config_path).unwrap();
        cfg.validate().unwrap();
        assert_eq!(cfg.listen_addr.port(), 7000);
        assert!(cfg.listen_addr.ip().is_loopback());
        assert_eq!(cfg.public_url, "https://fleet.example");
        // The `[tls]` block is commented out: plain HTTP behind a proxy is the
        // default, and generating a certificate nobody asked for is how you end
        // up with a self-signed cert in production.
        assert!(cfg.tls.is_none());
        // `[github]` is commented out for the same reason: an empty table with no
        // client_id fails validation. The next-steps text therefore says to
        // UNCOMMENT it — uncommenting it here means fixing that text too.
        let raw = std::fs::read_to_string(&config_path).unwrap();
        assert!(
            !raw.lines().any(|l| l.trim_start().starts_with("[github]")),
            "[github] must stay commented out"
        );
    }

    #[test]
    fn public_url_defaults_to_the_loopback_listener() {
        let tmp = tempfile::tempdir().unwrap();
        run(InitArgs {
            config_dir: Some(tmp.path().join("config")),
            data_dir: Some(tmp.path().join("data")),
            public_url: None,
            force: false,
        })
        .unwrap();
        let cfg =
            config::load_coordinator_config(&tmp.path().join("config").join(CONFIG_FILE)).unwrap();
        assert_eq!(cfg.public_url, "http://127.0.0.1:7000");
        cfg.validate().unwrap();
    }

    #[test]
    fn refuses_overwrite_without_force() {
        let tmp = tempfile::tempdir().unwrap();
        init_into(tmp.path(), false).unwrap();

        let seed_path = tmp.path().join("data").join(SIGNING_SEED_FILE);
        let before = std::fs::read_to_string(&seed_path).unwrap();

        // Second run without --force must fail and leave files untouched.
        assert!(init_into(tmp.path(), false).is_err());
        let after = std::fs::read_to_string(&seed_path).unwrap();
        assert_eq!(before, after);

        // With --force, regeneration succeeds and rewrites the seed.
        init_into(tmp.path(), true).unwrap();
        let forced = std::fs::read_to_string(&seed_path).unwrap();
        assert_ne!(before, forced);
    }

    #[test]
    fn defaults_to_coordinator_subdir_under_xdg() {
        use crate::test_support::ENV_LOCK;

        let _guard = ENV_LOCK
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);

        let prev_config = std::env::var_os("XDG_CONFIG_HOME");
        let prev_data = std::env::var_os("XDG_DATA_HOME");
        let prev_home = std::env::var_os("HOME");

        let tmp = tempfile::tempdir().unwrap();
        let config_root = tmp.path().join("config");
        let data_root = tmp.path().join("data");

        // SAFETY of correctness (not memory): guarded by ENV_LOCK above.
        std::env::set_var("XDG_CONFIG_HOME", &config_root);
        std::env::set_var("XDG_DATA_HOME", &data_root);
        std::env::set_var("HOME", tmp.path());

        // No --config-dir / --data-dir: must default to the per-role subdir.
        let result = run(InitArgs {
            config_dir: None,
            data_dir: None,
            public_url: None,
            force: false,
        });

        // Restore env before asserting so a failure cannot leak overrides.
        restore_env("XDG_CONFIG_HOME", prev_config);
        restore_env("XDG_DATA_HOME", prev_data);
        restore_env("HOME", prev_home);

        result.unwrap();

        let config = config_root.join("probe-rs-fleet").join("coordinator");
        let data = data_root.join("probe-rs-fleet").join("coordinator");
        assert!(
            config.join(CONFIG_FILE).exists(),
            "config must land under coordinator/ subdir: {}",
            config.join(CONFIG_FILE).display()
        );
        assert!(
            data.join(SIGNING_SEED_FILE).exists(),
            "seed must land under coordinator/ subdir: {}",
            data.join(SIGNING_SEED_FILE).display()
        );
    }

    fn restore_env(key: &str, prev: Option<std::ffi::OsString>) {
        // SAFETY of correctness (not memory): callers hold ENV_LOCK.
        match prev {
            Some(v) => std::env::set_var(key, v),
            None => std::env::remove_var(key),
        }
    }
}
